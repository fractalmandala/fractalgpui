/**
 * `bun run dist:dmg` — packages fractalgpui as a drag-install macOS disk image:
 *
 *   build/output/fractalgpui.app   (bundle: launcher, bun, app sources, node_modules,
 *                                   fractalstyler's style sources, icon)
 *   build/output/fractalgpui.dmg   (the .app + an /Applications symlink)
 *
 * The app compiles its styles at startup from fractalstyler's *source*, so the bundle
 * carries `packages/fractalstyler/src/lib/styles` and points FRACTALSTYLER_STYLES at
 * it. The bundled bun is this machine's (arm64). Unsigned; build/output is gitignored.
 */

import { execFileSync } from 'node:child_process';
import { chmodSync, cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FRACTALSTYLER_STYLES } from './fractalstyler.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'build/output');
const NAME = 'fractalgpui';
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const run = (cmd: string, args: string[], cwd = ROOT) => execFileSync(cmd, args, { cwd, stdio: 'inherit' });

const APP = join(OUT, `${NAME}.app`);
const CONTENTS = join(APP, 'Contents');
const RES = join(CONTENTS, 'Resources');
const DMG = join(OUT, `${NAME}.dmg`);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(CONTENTS, 'MacOS'), { recursive: true });
mkdirSync(RES, { recursive: true });

// 1. The app itself: sources, assets the runtime reads, and production node_modules.
const app = join(RES, 'app');
for (const p of ['app.ts', 'package.json', 'tsconfig.json', 'src', 'assets/icons']) cpSync(join(ROOT, p), join(app, p), { recursive: true });
for (const f of readdirSync(join(ROOT, 'build'))) if (f !== 'output' && !f.endsWith('.swift')) cpSync(join(ROOT, 'build', f), join(app, 'build', f), { recursive: true });
const DEV_ONLY = ['typescript', '@types'];
cpSync(join(ROOT, 'node_modules'), join(app, 'node_modules'), {
	recursive: true,
	verbatimSymlinks: true,
	filter: (src) => !DEV_ONLY.some((d) => src.startsWith(join(ROOT, 'node_modules', d)))
});
cpSync(FRACTALSTYLER_STYLES, join(RES, 'fractalstyler/styles'), { recursive: true });

// 2. The runtime: this machine's bun.
const bun = process.execPath;
cpSync(bun, join(RES, 'bun'));
chmodSync(join(RES, 'bun'), 0o755);

// 3. Launcher: bundled bun on PATH (gpuix-svelte re-spawns `bun`), styles from the bundle.
const launcher = join(CONTENTS, 'MacOS', NAME);
writeFileSync(
	launcher,
	`#!/bin/sh
# fractalgpui launcher (generated by build/dmg.ts)
RES="$(cd "$(dirname "$0")/../Resources" && pwd)"
export PATH="$RES:$PATH"
export FRACTALSTYLER_STYLES="$RES/fractalstyler/styles"
cd "$RES/app" || exit 1
exec "$RES/bun" node_modules/gpuix-svelte/bin/gpuix-svelte.js --bun app.ts "$@"
`
);
chmodSync(launcher, 0o755);

// 4. Icon: assets/app-icon.png (1024px), as an .icns.
const iconset = join(OUT, `${NAME}.iconset`);
mkdirSync(iconset);
const png = join(ROOT, 'assets/app-icon.png');
for (const s of [16, 32, 128, 256, 512]) {
	run('sips', ['-z', String(s), String(s), png, '--out', join(iconset, `icon_${s}x${s}.png`)]);
	run('sips', ['-z', String(s * 2), String(s * 2), png, '--out', join(iconset, `icon_${s}x${s}@2x.png`)]);
}
run('iconutil', ['-c', 'icns', iconset, '-o', join(RES, `${NAME}.icns`)]);
rmSync(iconset, { recursive: true });

// 5. Info.plist.
writeFileSync(
	join(CONTENTS, 'Info.plist'),
	`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleName</key><string>${NAME}</string>
	<key>CFBundleDisplayName</key><string>${NAME}</string>
	<key>CFBundleIdentifier</key><string>com.fractalmandala.fractalgpui</string>
	<key>CFBundleExecutable</key><string>${NAME}</string>
	<key>CFBundleIconFile</key><string>${NAME}</string>
	<key>CFBundlePackageType</key><string>APPL</string>
	<key>CFBundleShortVersionString</key><string>${pkg.version}</string>
	<key>CFBundleVersion</key><string>${pkg.version}</string>
	<key>LSMinimumSystemVersion</key><string>13.0</string>
	<key>LSArchitecturePriority</key><array><string>arm64</string></array>
	<key>NSHighResolutionCapable</key><true/>
	<key>NSPrincipalClass</key><string>NSApplication</string>
</dict>
</plist>
`
);

// 6. The disk image: the .app and an /Applications symlink, for drag-install.
const stage = join(OUT, 'dmg-stage');
mkdirSync(stage);
run('ditto', [APP, join(stage, `${NAME}.app`)]);
symlinkSync('/Applications', join(stage, 'Applications'));
run('hdiutil', ['create', '-volname', NAME, '-srcfolder', stage, '-ov', '-format', 'UDZO', DMG]);
rmSync(stage, { recursive: true });

const mb = (statSync(DMG).size / 1024 / 1024).toFixed(1);
console.log(`\n${DMG} (${mb} MB)`);
